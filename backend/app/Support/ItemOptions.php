    /** field => its choices (in the given order, duplicates dropped) */
    public static function categories(): array
    {
        $list = fn (string $txt) => array_values(array_unique(array_filter(array_map('trim', explode("\n", $txt)), fn ($v) => $v !== '')));

        return [
            'accurate_category_induk' => $list(self::INDUK),
            'accurate_category_anak_1' => $list(self::ANAK_1),
            'accurate_category_anak_2' => $list(self::ANAK_2),
            'accurate_category_anak_3' => $list(self::ANAK_3),
        ];
    }

    /**
     * Validation of the category fields: one of the choices — or the value the item already has
     * (an Accurate item may carry a category outside the list; saving it again keeps it).
     */
    public static function rules(?object $item = null): array
    {
        $rules = [];
        foreach (self::categories() as $field => $choices) {
            $rules[$field] = ['nullable', 'string', 'max:200', function (string $attr, mixed $value, \Closure $fail) use ($choices, $item, $field) {
                if ($value !== null && ! in_array($value, $choices, true) && $value !== ($item?->{$field} ?? null)) {
                    $fail('Pilih dari daftar yang tersedia.');
                }
            }];
        }

        return $rules;
    }
